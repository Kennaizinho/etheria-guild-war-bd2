-- Etheria Guild War - modelo relacional normalizado (3FN)
-- Banco: PostgreSQL 16+. Instalação inicial pelo Docker Compose.
CREATE TABLE IF NOT EXISTS guilda (
    id_guilda BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS jogador (
    id_jogador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(150) NOT NULL UNIQUE,
    CONSTRAINT ck_jogador_nome CHECK (length(btrim(nickname)) > 0)
);

CREATE TABLE IF NOT EXISTS membro_guilda (
    id_membro VARCHAR(80) PRIMARY KEY,
    id_guilda BIGINT NOT NULL REFERENCES guilda(id_guilda) ON DELETE CASCADE,
    id_jogador BIGINT NOT NULL REFERENCES jogador(id_jogador) ON DELETE RESTRICT,
    cargo VARCHAR(30) NOT NULL DEFAULT 'membro',
    avatar VARCHAR(150) NOT NULL DEFAULT 'Airon',
    CONSTRAINT uq_membro_por_guilda UNIQUE (id_guilda, id_jogador),
    CONSTRAINT ck_cargo CHECK (cargo IN ('lider','vice','membro'))
);

CREATE TABLE IF NOT EXISTS heroi (
    id_heroi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS carta (
    id_carta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS pet (
    id_pet BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS batalha (
    id_batalha BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    data_batalha DATE NOT NULL,
    resultado VARCHAR(12) NOT NULL CHECK (resultado IN ('Vitória','Derrota')),
    id_atacante BIGINT NOT NULL REFERENCES jogador(id_jogador) ON DELETE RESTRICT,
    id_defensor BIGINT NOT NULL REFERENCES jogador(id_jogador) ON DELETE RESTRICT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_jogadores_distintos CHECK (id_atacante <> id_defensor)
);

CREATE TABLE IF NOT EXISTS composicao_batalha (
    id_composicao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_batalha BIGINT NOT NULL REFERENCES batalha(id_batalha) ON DELETE CASCADE,
    lado VARCHAR(8) NOT NULL CHECK (lado IN ('atacante','defensor')),
    slot SMALLINT NOT NULL CHECK (slot BETWEEN 1 AND 3),
    id_heroi BIGINT NOT NULL REFERENCES heroi(id_heroi) ON DELETE RESTRICT,
    id_carta BIGINT NOT NULL REFERENCES carta(id_carta) ON DELETE RESTRICT,
    id_pet BIGINT NOT NULL REFERENCES pet(id_pet) ON DELETE RESTRICT,
    CONSTRAINT uq_composicao_lado_slot UNIQUE (id_batalha, lado, slot)
);
