let baseEntidades = { herois: [], pets: [], cartas: [] };
let defesaAtual = [{ heroi: null, pet: null, carta: null }, { heroi: null, pet: null, carta: null }, { heroi: null, pet: null, carta: null }];
let targetSlot = null; let targetType = null; let sugestoesParciaisSalvas = []; 

function inicializarConstrutor() {
    fetch('/api/entidades').then(r => r.json()).then(data => {
        baseEntidades = data; entidadesCarregadas = true; renderizarSlotsConstrutor();
    });
}

function renderizarSlotsConstrutor() {
    const container = document.getElementById('area-slots');
    let html = '';
    defesaAtual.forEach((slot, idx) => {
        let imgHero = slot.heroi ? `<img ${atributosImagemAsset('PersonagensFullBody', slot.heroi, true)} loading="lazy" decoding="async">` : `+ ${t('heroi')}`;
        let imgPet = slot.pet ? `<img ${atributosImagemAsset('Pets', slot.pet)} loading="lazy" decoding="async">` : `+ ${t('pet')}`;
        let imgCarta = slot.carta ? `<img ${atributosImagemAsset('Cards', slot.carta)} loading="lazy" decoding="async">` : `+ ${t('carta')}`;
        let btnLimpar = (slot.heroi || slot.pet || slot.carta) ? `<button class="btn-limpar" onclick="limparSlot(${idx}, event)">${t('limpar')}</button>` : '';

        html += `
        <div class="slot-construtor">
            ${btnLimpar}
            <div class="box-add" onclick="abrirModal(${idx}, 'heroi')">${imgHero}</div>
            <div class="sub-box-container">
                <div class="sub-box" onclick="abrirModal(${idx}, 'pet')">${imgPet}</div>
                <div class="sub-box" onclick="abrirModal(${idx}, 'carta')">${imgCarta}</div>
            </div>
        </div>`;
    });
    container.innerHTML = html;
}

function limparSlot(idx, event) {
    event.stopPropagation(); defesaAtual[idx] = { heroi: null, pet: null, carta: null };
    renderizarSlotsConstrutor(); verificarESugerir();
}

function obterHeroisSelecionados() {
    return new Set(defesaAtual.map(slot => slot.heroi).filter(Boolean));
}

function abrirModal(idx, tipo) {
    targetSlot = idx; targetType = tipo;
    const grid = document.getElementById('modal-grid');
    let txtModal = tipo === 'heroi' ? t('selecionar-personagem') : tipo === 'pet' ? t('selecionar-pet') : t('selecionar-carta');
    document.getElementById('modal-titulo').innerText = txtModal;
    
    let itens = tipo === 'heroi' ? baseEntidades.herois : tipo === 'pet' ? baseEntidades.pets : baseEntidades.cartas;
    const heroisSelecionados = tipo === 'heroi' ? obterHeroisSelecionados() : new Set();
    grid.innerHTML = '';

    itens.forEach(item => {
        let imgAttrs = tipo === 'heroi' ? atributosImagemAsset('PersonagensFullBody', item, true) : tipo === 'pet' ? atributosImagemAsset('Pets', item) : atributosImagemAsset('Cards', item);
        let imgClass = tipo === 'heroi' ? 'item-img-full' : 'item-img-small';
        const indisponivel = tipo === 'heroi' && heroisSelecionados.has(item);
        const classeIndisponivel = indisponivel ? ' item-selecao-indisponivel' : '';
        const atributosInteracao = indisponivel
            ? 'aria-disabled="true"'
            : `onclick="selecionarItem('${item}')"`;

        grid.innerHTML += `
        <div class="item-selecao${classeIndisponivel}" ${atributosInteracao}>
            <img ${imgAttrs} class="${imgClass}" loading="lazy" decoding="async">
            <div class="item-name">${item}</div>
        </div>`;
    });
    document.getElementById('modal-selecao').style.display = 'flex';
}

function fecharModal() { document.getElementById('modal-selecao').style.display = 'none'; }

function selecionarItem(nomeItem) {
    if (targetType === 'heroi') {
        const jaUsadoEmOutroSlot = defesaAtual.some((slot, idx) => idx !== targetSlot && slot.heroi === nomeItem);
        if (jaUsadoEmOutroSlot) return;
    }

    defesaAtual[targetSlot][targetType] = nomeItem;
    fecharModal(); renderizarSlotsConstrutor(); verificarESugerir();
}

function verificarESugerir() {
    let completo = defesaAtual.every(s => s.heroi !== null);
    if (!completo) {
        document.getElementById('area-sugestoes').innerHTML = `
            <div style="text-align: center; color: var(--border-light); margin-top: 50px;">
                <span style="font-size: 40px; display: block; margin-bottom: 10px;">🛡️</span>
                <span>${t('construtor-placeholder')}</span>
            </div>`;
        return;
    }

    fetch('/api/sugerir-ataque', {
        method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(defesaAtual)
    }).then(r => r.json()).then(resposta => {
        const container = document.getElementById('area-sugestoes');
        
        if (resposta.tipo === "nenhum" || resposta.dados.length === 0) {
            container.innerHTML = `<p style="text-align:center; color: var(--text-secondary); margin-top:50px;">${t('sem-dados')}</p>`;
            return;
        }

        if (resposta.tipo === "parcial") {
            sugestoesParciaisSalvas = resposta.dados; 
            container.innerHTML = `
                <div style="text-align: center; margin-top: 40px; background-color: var(--bg-surface); padding: 35px 25px; border-radius: 12px; border: 1px dashed var(--border-light);">
                    <span style="font-size: 45px; display: block; margin-bottom: 15px;">🤔</span>
                    <h3 style="margin: 0 0 10px 0; color: var(--text-primary); font-size: 20px;">${t('nao-temos-dados')}</h3>
                    <p style="color: var(--text-secondary); font-size: 15px; margin-bottom: 25px; line-height: 1.6;">${t('aviso-novo-1')}</p>
                    <p style="color: var(--text-primary); font-size: 14px; margin-bottom: 25px;">${t('aviso-novo-2')}</p>
                    <button class="btn-acao" style="background-color: var(--accent); color: white; padding: 12px 25px;" onclick="renderizarHTMLSugestoes(true)">${t('btn-mostrar-sugestao')}</button>
                </div>`;
            return;
        }
        sugestoesParciaisSalvas = resposta.dados; renderizarHTMLSugestoes(false);
    });
}

