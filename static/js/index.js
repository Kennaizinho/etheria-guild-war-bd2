function abrirView(idView, botao) {
    document.querySelectorAll('.btn-acao').forEach(b => b.classList.remove('active'));
    if(botao) botao.classList.add('active');

    document.querySelectorAll('.view-section').forEach(v => v.classList.remove('active'));
    document.getElementById(idView).classList.add('active');

    const container = document.getElementById('main-container');
    const titulo = document.getElementById('titulo-guilda');
    const subTexto = document.getElementById('sub-texto');
    
    if (idView === 'view-guildas') {
        container.className = 'container';
        const guildaAtiva = document.querySelector('.guild-card.active');
        if (guildaAtiva) {
            titulo.style.display = 'block';
            subTexto.style.display = 'none';
        } else {
            titulo.style.display = 'none';
            subTexto.innerHTML = t("sub-texto-guilda");
            subTexto.style.display = 'block';
        }
    } else if (idView === 'view-defesas') {
        container.className = 'container expanded';
        titulo.style.display = 'none';
        subTexto.innerHTML = t("sub-texto-defesas");
        subTexto.style.display = 'block';
        if (!defesasGlobaisCarregadas) buscarDefesasGlobais();
    } else if (idView === 'view-enfrentar') {
        container.className = 'container mega-expanded';
        titulo.style.display = 'none';
        subTexto.innerHTML = t("sub-texto-enfrentar");
        subTexto.style.display = 'block';
        if (!entidadesCarregadas) inicializarConstrutor();
    } else if (idView === 'view-calendario') {
        container.className = 'container mega-expanded';
        titulo.style.display = 'none';
        subTexto.innerHTML = t("sub-texto-calendario");
        subTexto.style.display = 'block';

        // Agora que a view está visível, temos a largura real da grade.
        requestAnimationFrame(() => {
            atualizarIndicadorHoje();
            centralizarHojeNoCalendario();
        });
    }
}
