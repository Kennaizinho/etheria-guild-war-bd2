// Calendário SS6: 91 dias, de 02/09/2026 até 02/12/2026.
// O marcador usa a data local do navegador e fica no centro do dia atual.
const CALENDAR_START = new Date(2026, 8, 2, 0, 0, 0, 0);
const CALENDAR_END = new Date(2026, 11, 2, 0, 0, 0, 0);
const CALENDAR_SIDEBAR_WIDTH = 120;

function atualizarIndicadorHoje() {
    const line = document.getElementById('cg-today-line');
    const label = document.getElementById('cg-today-label');
    const inner = document.querySelector('#view-calendario .cg-inner');
    if (!line || !label || !inner) return;

    const agora = new Date();
    // Meio-dia mantém o indicador visualmente no centro da coluna do dia,
    // sem depender da hora em que o visitante abriu a página.
    const hoje = new Date(
        agora.getFullYear(),
        agora.getMonth(),
        agora.getDate(),
        12, 0, 0, 0
    );

    if (hoje < CALENDAR_START || hoje >= CALENDAR_END) {
        line.style.display = 'none';
        return;
    }

    line.style.display = 'block';

    const larguraTotal = inner.getBoundingClientRect().width;
    // A view pode estar display:none durante o carregamento inicial.
    // Nesse caso, a posição será recalculada assim que o calendário abrir.
    if (!larguraTotal) return;

    const larguraTimeline = larguraTotal - CALENDAR_SIDEBAR_WIDTH;
    const totalMs = CALENDAR_END - CALENDAR_START;
    const decorridoMs = hoje - CALENDAR_START;
    const proporcao = Math.max(0, Math.min(1, decorridoMs / totalMs));
    const x = CALENDAR_SIDEBAR_WIDTH + (proporcao * larguraTimeline);

    line.style.left = `${x}px`;

    const mesesPT = ['jan', 'fev', 'mar', 'abr', 'mai', 'jun', 'jul', 'ago', 'set', 'out', 'nov', 'dez'];
    const mesesEN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    label.textContent = currentLang === 'pt'
        ? `Hoje · ${agora.getDate()} ${mesesPT[agora.getMonth()]}`
        : `Today · ${mesesEN[agora.getMonth()]} ${agora.getDate()}`;

    line.dataset.currentDate = [
        agora.getFullYear(),
        String(agora.getMonth() + 1).padStart(2, '0'),
        String(agora.getDate()).padStart(2, '0')
    ].join('-');
}

function centralizarHojeNoCalendario() {
    const wrap = document.querySelector('#view-calendario .cg-wrap');
    const line = document.getElementById('cg-today-line');
    if (!wrap || !line || line.style.display === 'none') return;

    const x = parseFloat(line.style.left);
    if (!Number.isFinite(x)) return;

    const destino = Math.max(0, x - (wrap.clientWidth / 2));
    wrap.scrollTo({ left: destino, behavior: 'smooth' });
}

function toggleLanguage() {
    currentLang = currentLang === 'pt' ? 'en' : 'pt';
    localStorage.setItem('lang', currentLang);
    location.reload(); 
}

